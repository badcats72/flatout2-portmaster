"""Writes runtime/native/fo2_text_tables.h: the switch tables that the lifted code reads in the exe's .text.

The lifted code keeps the game's switches as "jmp [index*4 + table]" (and "movzx index, byte [value + index_table]")
read from guest memory. Those tables sit in .text, which a DRM wrapper encrypts and a protected retail copy rewrites, so
an exe of the same build whose code differs could not run. The tables hold only code addresses and small indices: they
are taken here from the lifted exe and written back by the runtime over a copy whose code differs (loadImage).

    python scripts/make_text_tables.py work/lift/FlatOut2.exe work/gen runtime/native/fo2_text_tables.h
"""
import glob
import os
import re
import sys

import pefile

TEXT_LO, TEXT_HI = 0x401000, 0x652000
JT = re.compile(r'_jt = MEM32\(\w+ \* 4 \+ 0x([0-9A-F]+)\)')
CASE = re.compile(r'case 0x([0-9A-F]+)u:')
BYTE = re.compile(r'MEM8\(\w+ \+ 0x([0-9A-F]+)\)')
CMP = re.compile(r'/\* cmp [^,]+, (0x[0-9a-fA-F]+|\d+)u? \*/')


def main(exe, gen, out):
    pe = pefile.PE(exe)
    img = pe.get_memory_mapped_image()
    base = pe.OPTIONAL_HEADER.ImageBase
    rd32 = lambda va: int.from_bytes(img[va - base:va - base + 4], 'little')
    targets = {}      # dword table -> possible targets
    byte_sizes = {}   # index table -> entries
    for path in sorted(glob.glob(os.path.join(gen, 'recomp_*.c'))):
        lines = open(path, encoding='utf-8', errors='replace').read().split('\n')
        for i, line in enumerate(lines):
            m = JT.search(line)
            if m:
                t = int(m.group(1), 16)
                if TEXT_LO <= t < TEXT_HI:
                    cases = targets.setdefault(t, set())
                    for follow in lines[i + 1:i + 400]:
                        c = CASE.search(follow)
                        if c:
                            cases.add(int(c.group(1), 16))
                        elif 'default:' in follow:
                            break
            m = BYTE.search(line)
            if m:
                t = int(m.group(1), 16)
                if TEXT_LO <= t < TEXT_HI:
                    size = None
                    for back in reversed(lines[max(0, i - 16):i]):
                        c = CMP.search(back)
                        if c:
                            size = int(c.group(1), 0) + 1
                            break
                    if size is None or size > 1024:
                        raise SystemExit('no bound for the index table at %08x (%s:%d)' % (t, path, i + 1))
                    byte_sizes[t] = max(byte_sizes.get(t, 0), size)
    def entry(t, i, cases):
        # A case of the switch, or a code address close to the table: the lifter's case list can miss the real
        # targets (memcpy's backward copy), which then go through the dynamic dispatch, still reading the table.
        v = rd32(t + 4 * i)
        return v in cases or (TEXT_LO <= v < TEXT_HI and abs(v - t) < 0x2000)

    regions = []
    for t, cases in targets.items():
        # Entries up to the last valid one (a few are never used: memcpy's entry 0 is code).
        last, misses = -1, 0
        for i in range(1024):
            if entry(t, i, cases):
                last, misses = i, 0
            else:
                misses += 1
                if (last >= 0 and misses >= 2) or (last < 0 and i >= 3):
                    break
        n = last + 1
        # Negative indices too: the CRT's memcpy / memmove index some tables from below (sub ecx, 4; jmp [ecx*4 + table]).
        first, misses = 0, 0
        for i in range(-1, -64, -1):
            if entry(t, i, cases):
                first, misses = i, 0
            else:
                misses += 1
                if misses >= 2:
                    break
        if not n and not first:   # no entry is a case: a path the game never takes
            print('skipped: no case in the table at %08x' % t)
            continue
        regions.append((t + 4 * first, 4 * (max(n, 0) - first)))
    regions += [(t, n) for t, n in byte_sizes.items()]
    regions.sort()
    merged = []
    for va, n in regions:
        if merged and va <= merged[-1][0] + merged[-1][1]:
            merged[-1][1] = max(merged[-1][1], va + n - merged[-1][0])
        else:
            merged.append([va, n])
    blob = b''.join(img[va - base:va - base + n] for va, n in merged)
    lines = [
        '// Generated by scripts/make_text_tables.py from the lifted FlatOut2.exe: do not edit.',
        '// The switch tables the lifted code reads in .text (code addresses and indices only).',
        '#pragma once',
        '#include <cstdint>',
        'namespace fo2exe {',
        'struct TextTable { uint32_t va, size, offset; };',
        'constexpr TextTable kTextTables[] = {',
    ]
    off = 0
    for va, n in merged:
        lines.append('    {0x%08xu, %u, %u},' % (va, n, off))
        off += n
    lines += ['};', 'constexpr uint8_t kTextTableBytes[] = {']
    for i in range(0, len(blob), 24):
        lines.append('    ' + ', '.join('0x%02x' % b for b in blob[i:i + 24]) + ',')
    lines += ['};', '}  // namespace fo2exe', '']
    open(out, 'w', newline='\n').write('\n'.join(lines))
    print('%d dword tables, %d index tables -> %d regions, %d bytes -> %s' % (len(targets), len(byte_sizes), len(merged), len(blob), out))


if __name__ == '__main__':
    main(*sys.argv[1:4])
