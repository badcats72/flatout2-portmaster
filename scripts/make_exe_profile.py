"""Writes runtime/native/fo2_exe_profile.h from the exe the code was lifted from (work/lift/FlatOut2.exe).

The profile lets the runtime accept other copies of the same build (GOG, Steam, retail patch 1.2...), whose file
differs from the lifted one in its wrapper, headers or a few strings, and refuse the others with a clear message:
  - one FNV-1a 64 hash per 4 KB page of what the loader maps from every section but .reloc (the lifted code
    still reads .text: its switch tables)
    (hashes only: no byte of the game is copied into the header);
  - the import slots (DLL, function, IAT address), so the runtime can bind them even when the file's own
    import table is missing or wrapped (a DRM stub's).

    python scripts/make_exe_profile.py work/lift/FlatOut2.exe runtime/native/fo2_exe_profile.h
"""
import sys
import pefile

PAGE = 0x1000


def fnv(data):
    h = 0xcbf29ce484222325
    for b in data:
        h = ((h ^ b) * 0x100000001b3) & 0xffffffffffffffff
    return h


def main(exe, out):
    pe = pefile.PE(exe)
    raw = open(exe, 'rb').read()
    base = pe.OPTIONAL_HEADER.ImageBase
    pages = []
    for s in pe.sections:
        name = s.Name.rstrip(b'\0').decode()
        if name == '.reloc':
            continue
        kind = 2 if name == '.text' else 1 if name in ('.rdata', '.data') else 0
        data = raw[s.PointerToRawData:s.PointerToRawData + s.SizeOfRawData]
        for off in range(0, len(data), PAGE):
            page = data[off:off + PAGE].ljust(PAGE, b'\0')
            pages.append((base + s.VirtualAddress + off, fnv(page), kind, name))
    imports = []
    for d in pe.DIRECTORY_ENTRY_IMPORT:
        for i in d.imports:
            name = i.name.decode() if i.name else '#%d' % i.ordinal
            imports.append((i.address, d.dll.decode().lower(), name))
    lines = [
        '// Generated by scripts/make_exe_profile.py from the FlatOut2.exe the code was lifted from: do not edit.',
        '// Page hashes and import names only (see the script). Used by loadImage (guest_runtime.cpp).',
        '#pragma once',
        '#include <cstdint>',
        'namespace fo2exe {',
        'constexpr uint32_t kTimeDateStamp = 0x%08xu, kEntryRva = 0x%08xu, kSizeOfImage = 0x%08xu;' % (
            pe.FILE_HEADER.TimeDateStamp, pe.OPTIONAL_HEADER.AddressOfEntryPoint, pe.OPTIONAL_HEADER.SizeOfImage),
        'struct Page { uint32_t va; uint64_t hash; uint8_t kind; };   // kind: 2 = .text, 1 = .rdata / .data, 0 = other sections',
        'constexpr Page kPages[] = {',
    ]
    lines += ['    {0x%08xu, 0x%016xull, %d},  // %s' % (va, h, k, n) for va, h, k, n in pages]
    lines += ['};', 'struct Import { uint32_t slot; const char* dll; const char* name; };', 'constexpr Import kImports[] = {']
    lines += ['    {0x%08xu, "%s", "%s"},' % imp for imp in imports]
    lines += ['};', '}  // namespace fo2exe', '']
    open(out, 'w', newline='\n').write('\n'.join(lines))
    print('%d pages, %d imports -> %s' % (len(pages), len(imports), out))


if __name__ == '__main__':
    main(*sys.argv[1:3])
